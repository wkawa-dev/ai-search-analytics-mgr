"""Config + state on disk. Everything lives under one directory (override with ASAM_HOME)."""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

KNOWN_KEYS = {
    "default_site": "GSC property or domain used when `site` is omitted (e.g. example.com or sc-domain:example.com)",
    "default_property": "GA4 property used when `property` is omitted (e.g. 123456789)",
    "brand_terms": "Comma-separated brand terms for brand vs non-brand split (default: derived from domain)",
    "google_api_key": "Optional API key for PageSpeed Insights / CrUX (higher quota). Env: ASAM_GOOGLE_API_KEY",
    "indexnow_key": "IndexNow key (generated by `asam indexnow key`)",
    "credentials_file": "Path to service-account JSON or authorized-user JSON (overrides token.json)",
    "impersonate": "Service account domain-wide delegation subject (user email), optional",
    "cache_ttl_seconds": "Cache TTL for report queries (default 21600 = 6h; 0 disables)",
    "reports_dir": "Where full reports / large exports are written (default ./asam-reports)",
    "site_properties": "Learned mapping of domain -> GA4 property id (managed automatically)",
}


def home() -> Path:
    env = os.environ.get("ASAM_HOME")
    if env:
        p = Path(env).expanduser()
    else:
        base = os.environ.get("XDG_CONFIG_HOME") or str(Path.home() / ".config")
        p = Path(base) / "asam"
    p.mkdir(parents=True, exist_ok=True)
    try:
        os.chmod(p, 0o700)
    except OSError:
        pass
    return p


def cache_dir() -> Path:
    base = os.environ.get("XDG_CACHE_HOME") or str(Path.home() / ".cache")
    p = Path(os.environ.get("ASAM_CACHE_DIR") or (Path(base) / "asam"))
    p.mkdir(parents=True, exist_ok=True)
    return p


def config_path() -> Path:
    return home() / "config.json"


def load() -> dict[str, Any]:
    p = config_path()
    if not p.exists():
        return {}
    try:
        return json.loads(p.read_text())
    except json.JSONDecodeError:
        return {}


def save(cfg: dict[str, Any]) -> None:
    write_secret(config_path(), json.dumps(cfg, indent=2, sort_keys=True))


def get(key: str, default: Any = None) -> Any:
    env_key = "ASAM_" + key.upper()
    if env_key in os.environ:
        return os.environ[env_key]
    return load().get(key, default)


def set_value(key: str, value: Any) -> dict[str, Any]:
    cfg = load()
    if value is None or value == "":
        cfg.pop(key, None)
    else:
        cfg[key] = value
    save(cfg)
    return cfg


def remember_property(domain: str, property_id: str) -> None:
    cfg = load()
    m = cfg.setdefault("site_properties", {})
    if m.get(domain) != property_id:
        m[domain] = property_id
        save(cfg)


def reports_dir() -> Path:
    p = Path(get("reports_dir") or "asam-reports").expanduser()
    p.mkdir(parents=True, exist_ok=True)
    return p


def write_secret(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(str(path), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(content)
